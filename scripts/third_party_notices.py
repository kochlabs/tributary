#!/usr/bin/env python3
"""Generates THIRD_PARTY_NOTICES.md: the licenses of every Go module compiled
into nfad (with their full license and NOTICE texts, as Apache-2.0, MIT and
BSD require for binary distribution), the web UI's runtime dependencies, and
the data sources Tributary can use.

Run via `make notices` after changing dependencies."""
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LICENSE_FILE = re.compile(r'^(LICEN[CS]E|COPYING|NOTICE|PATENTS)([-_.].*)?$', re.I)


def classify(text):
    t = ' '.join(text.split())
    if 'Apache License' in t and 'Version 2.0' in t:
        return 'Apache-2.0'
    if 'Mozilla Public License' in t and '2.0' in t:
        return 'MPL-2.0'
    if 'Permission is hereby granted, free of charge' in t:
        return 'MIT'
    if 'Redistribution and use in source and binary forms' in t:
        return 'BSD-3-Clause' if ('Neither the name' in t or 'names of its contributors' in t) else 'BSD-2-Clause'
    if 'Permission to use, copy, modify, and/or distribute' in t or 'ISC License' in t:
        return 'ISC'
    return 'see text'


def go_modules():
    out = subprocess.run(['go', 'list', '-deps', '-f', '{{if not .Standard}}{{with .Module}}{{if not .Main}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}{{end}}{{end}}', './cmd/nfad'],
                         cwd=ROOT, check=True, capture_output=True, text=True).stdout
    mods = {}
    for line in out.splitlines():
        path, version, d = line.split('\t')
        if d:  # Tributary's own module is excluded by the template
            mods[path] = (version, d)
    result = []
    for path in sorted(mods):
        version, d = mods[path]
        files = sorted(f for f in os.listdir(d) if LICENSE_FILE.match(f) and os.path.isfile(os.path.join(d, f)))
        if not files:
            sys.exit(f'{path}: no license file found')
        texts = [(f, open(os.path.join(d, f), encoding='utf-8', errors='replace').read().strip()) for f in files]
        main = next((t for f, t in texts if not f.upper().startswith(('NOTICE', 'PATENTS'))), texts[0][1])
        result.append((path, version, classify(main), texts))
    goroot = subprocess.run(['go', 'env', 'GOROOT'], check=True, capture_output=True, text=True).stdout.strip()
    gover = subprocess.run(['go', 'env', 'GOVERSION'], check=True, capture_output=True, text=True).stdout.strip()
    text = open(os.path.join(goroot, 'LICENSE')).read().strip()
    result.insert(0, ('Go standard library and runtime', gover, classify(text), [('LICENSE', text)]))
    return result


def web_packages():
    web = os.path.join(ROOT, 'web')
    deps = json.load(open(os.path.join(web, 'package.json')))['dependencies']
    seen, queue, out = set(), list(deps), []
    while queue:
        name = queue.pop()
        if name in seen:
            continue
        seen.add(name)
        pj = os.path.join(web, 'node_modules', name, 'package.json')
        if not os.path.exists(pj):
            continue
        p = json.load(open(pj))
        lic = p.get('license') or (p.get('licenses') or [{}])[0].get('type', 'see package')
        if isinstance(lic, dict):
            lic = lic.get('type', 'see package')
        out.append((name, p.get('version', ''), lic))
        queue.extend((p.get('dependencies') or {}).keys())
    return sorted(out)


def main():
    go = go_modules()
    web = web_packages()
    w = []
    w.append('# Third-party notices\n')
    w.append('Tributary is licensed under the GNU Affero General Public License v3.0 (see `LICENSE`).')
    w.append('It includes or uses the third-party components below, each under its own license.')
    w.append('This file is generated by `make notices`; do not edit it by hand.\n')
    w.append('## Data\n')
    w.append('| Data | Used for | License / terms |')
    w.append('|---|---|---|')
    w.append('| [DB-IP Lite](https://db-ip.com/db/lite.php) (downloaded at runtime when selected; the default) | Country and ASN of IP addresses | [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/). Attribution: "IP Geolocation by DB-IP" |')
    w.append('| [MaxMind GeoLite2 / GeoIP2](https://www.maxmind.com) (downloaded with your own account when selected) | Country and ASN of IP addresses | [GeoLite2 EULA](https://www.maxmind.com/en/geolite2/eula) or your MaxMind agreement. GeoLite2 attribution: "This product includes GeoLite2 data created by MaxMind" |')
    w.append('| [IEEE Registration Authority registries](https://standards.ieee.org/products-programs/regauth/) (downloaded weekly at runtime by default) | MAC address vendor names | Public listings published by the IEEE |')
    w.append('| [RIPEstat Data API](https://stat.ripe.net) (queried at runtime when enabled) | ASNs missing from the local database | [RIPEstat terms of use](https://www.ripe.net/about-us/legal/ripestat-service-terms-and-conditions/) |')
    w.append('')
    w.append('Tributary stores flows in [ClickHouse](https://clickhouse.com) (Apache-2.0), which is installed as a separate package and not distributed with Tributary.\n')
    w.append('## Web interface\n')
    w.append('Packages bundled into the web interface. Their full license texts ship with the interface as `3rdpartylicenses.txt` (generated by the Angular build).\n')
    w.append('| Package | Version | License |')
    w.append('|---|---|---|')
    for name, version, lic in web:
        w.append(f'| [{name}](https://www.npmjs.com/package/{name}) | {version} | {lic} |')
    w.append('')
    w.append('## Go modules\n')
    w.append('Modules compiled into the `nfad` binary.\n')
    w.append('| Module | Version | License |')
    w.append('|---|---|---|')
    for path, version, lic, _ in go:
        w.append(f'| {path} | {version} | {lic} |')
    w.append('')
    w.append('### License texts\n')
    for path, version, lic, texts in go:
        w.append(f'#### {path} {version}\n')
        for f, t in texts:
            w.append(f'`{f}`:\n')
            w.append('```text')
            w.append(t.replace('```', "'''"))
            w.append('```\n')
    open(os.path.join(ROOT, 'THIRD_PARTY_NOTICES.md'), 'w').write('\n'.join(w))
    print(f'THIRD_PARTY_NOTICES.md: {len(go)} Go modules, {len(web)} web packages')
    unknown = [p for p, _, l, _ in go if l == 'see text']
    if unknown:
        print('license not recognised (check by hand):', ', '.join(unknown))


if __name__ == '__main__':
    main()
